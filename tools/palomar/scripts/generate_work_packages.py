#!/usr/bin/env python3
"""Generate a fresh overlay from an explicitly supplied collected source or baseline fixture."""
import sys
if __name__ == "__main__":
    raise SystemExit("Use python3 -I -S -B /absolute/palomar.py generate ...; direct backend startup is unsupported")
sys.dont_write_bytecode = True
import argparse
import json
import os
from pathlib import Path
import shutil
import sys
import tempfile
import uuid

from work_package import (Invalid, VERSION, catalogs, digest, load_units, read_json, render, require, sha, verify_collection)
from boundaries import guard_paths, inputs_for, plan_outputs, exact_collection_tree, collection_layout
from work_package import json_bytes
import hashlib


def arguments(parser=None):
    p = parser or argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source", type=Path, required=True, help="explicit SAP source root; no implicit RC fallback")
    p.add_argument("--catalog", type=Path, required=True, help="frozen formal catalog directory")
    p.add_argument("--site", type=Path, required=True, help="site data/works directory")
    p.add_argument("--base-source", type=Path, help="explicit AronowAudit source root if source is SAP-only")
    p.add_argument("--kind", choices=("baseline_fixture", "collected_candidate"), required=True)
    p.add_argument("--attestation", type=Path)
    p.add_argument("--routes", type=Path)
    p.add_argument("--collection-receipt", type=Path, help="successful normal collection receipt, never a failed partial collection")
    p.add_argument("--collected-file-inventory", type=Path, help="complete file inventory hashed by the collection receipt")
    p.add_argument("--admission-root", type=Path, help="complete independently reviewed archived A3 admission evidence")
    p.add_argument("--admission-review", type=Path, help="independent parent review artifact; never generated by this tool")
    p.add_argument("--expected-admission-review-sha256", help="authority digest from independent parent review records")
    for flag in ("expected-admission-pin-sha256","expected-admission-result-sha256","expected-reviewed-tool-lock-sha256"):
        p.add_argument("--"+flag,help="expected actual artifact digest from independent parent review records")
    p.add_argument("--read-only-root", type=Path, action="append", default=[])
    return p


def tool_files():
    from _palomar_installation import blobs, entry_bytes
    files = {"tools/palomar/palomar.py":entry_bytes}
    files.update({"tools/palomar/"+name:data for name,data in blobs.items()})
    return files


def prepare(args):
    require(args.kind in ("baseline_fixture","collected_candidate"),"unsupported source kind")
    source = args.source.resolve()
    require(source.is_dir(), f"source snapshot absent: {source}; no RC fallback is permitted")
    formal, site = catalogs(args.catalog, args.site)
    attestation = read_json(args.attestation) if args.attestation else None
    routes = read_json(args.routes) if args.routes else None
    if args.kind == "collected_candidate":
        require(attestation is not None and routes is not None,
                "collected_candidate requires explicit --attestation AND --routes; baseline cannot be relabeled final")
        require(attestation.get("status") == "READ_ONLY_MATCH", "current source attestation is not a read-only match")
        require(attestation.get("unit_count") == len(attestation.get("units", [])), "attestation unit count mismatch")
        require(attestation.get("target_count") == sum(len(c["targets"]) for c in formal.values()),
                "attestation target count differs from catalog")
        require(getattr(args,"collected_file_inventory",None) is not None,
                "complete collected file inventory required")
        collection_layout(args.source, read_json(source/"SAP/INDEX.json"))
        exact_collection_tree(args.source, read_json(args.collected_file_inventory))
    else:
        require(attestation is None and routes is None, "baseline_fixture must not borrow current attestation/routes")
        require(not any(getattr(args,k,None) for k in ("admission_root","admission_review","expected_admission_review_sha256","expected_admission_pin_sha256","expected_admission_result_sha256","expected_reviewed_tool_lock_sha256")),
                "baseline_fixture cannot borrow independent real-collection approval")
    units = load_units(source, formal, attestation, routes)
    if attestation:
        require(set(units) == {u["unit"] for u in attestation["units"]}, "incomplete collected source")
    input_hashes = {"catalog/works.json": sha(args.catalog / "works.json"), "SAP/INDEX.json": sha(source / "SAP/INDEX.json")}
    input_hashes.update({f"catalog/works/{w}.json": sha(args.catalog / "works" / f"{w}.json") for w in formal})
    input_hashes.update({f"site/{w}.json": sha(args.site / f"{w}.json") for w in site})
    if attestation:
        input_hashes["current-81-source-attestation.json"] = sha(args.attestation)
        input_hashes["final-81-route-plan.json"] = sha(args.routes)
        input_hashes.update(verify_collection(source,args.attestation,getattr(args,"collection_receipt",None),
            getattr(args,"collected_file_inventory",None),units,sum(len(c["targets"]) for c in formal.values()),
            args=args,units=units))
    else:
        require(not getattr(args,"collection_receipt",None) and not getattr(args,"collected_file_inventory",None),
                "baseline_fixture must not borrow collection assurance")
    files = render(formal, site, units, source, args.kind, input_hashes, args.base_source)
    files.update(tool_files())
    files["OVERLAY-INVENTORY.json"] = json_bytes({"schema":"palomar-exact-overlay-v3", "source_kind":args.kind,
        "files_sha256":{p:hashlib.sha256(data).hexdigest() for p,data in sorted(files.items())},
        "self_excluded":"OVERLAY-INVENTORY.json"})
    return files


def main():
    parser = arguments()
    parser.add_argument("--out", type=Path, required=True, help="fresh output directory; must not exist")
    args = parser.parse_args()
    scratch=args.out.with_name("."+args.out.name+".scratch-"+uuid.uuid4().hex)
    planned=plan_outputs({"out":args.out,"scratch":scratch}, args,code_root=Path(__file__).resolve())
    args.out=planned["out"]
    require(not args.out.exists(), f"output exists; use a fresh generation: {args.out}")
    files = prepare(args)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    temp=planned["scratch"]
    temp.mkdir()
    try:
        for relative, content in files.items():
            dest = temp / relative
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(content)
        os.rename(temp, args.out)
    finally:
        if temp.exists():
            shutil.rmtree(temp)
    inv = read_json(args.out / "WORK-INVENTORY.json")
    print(json.dumps({"status": "structural_overlay_generated", "schema": VERSION, "source_kind": args.kind,
                      "counts": inv["counts"], "files": len(files), "content_sha256": digest({k: sha(args.out/k) for k in files}),
                      "combined_compilation": "not_run", "combined_certification": "not_run"}, sort_keys=True))


if __name__ == "__main__":
    try:
        main()
    except (Invalid, OSError, KeyError, TypeError) as exc:
        print(f"INVALID: {exc}", file=sys.stderr)
        sys.exit(1)
